test('stale data cannot change the baseline; genuine rollback is explicit', () => {
  const state = createLedger()
  apply(state, exp('2026-11-05T08:00:00', 100000))
  apply(state, exp('2026-11-04T08:00:00', 80000))
  assert.equal(state.baseline.exp, 100000)
  apply(state, exp('2026-11-05T09:00:00', 50000))
  assert.equal(state.events.at(-1).source, 'warning')
  assert.equal(state.baseline.exp, 100000)
  assert.equal(summarize(state, '2026-11').total, 0)
  apply(state, exp('2026-11-05T09:01:00', 101000, 1000))
  assert.equal(summarize(state, '2026-11').total, 0.7)
  assert.equal(summarize(state, '2026-11').unknown.length, 0)
})
test('timezone only changes display buckets; month-end activity is retained', () => {
  const state = createLedger()
  apply(state, exp('2026-11-01T00:30:00', 100000, 1000))
  assert.equal(summarize(state, '2026-11', 'Asia/Tokyo').total, 0.7)
  assert.equal(summarize(state, '2026-10', 'Asia/Shanghai').total, 0.7)
  apply(state, exp('2026-11-30T23:30:00', 101000, 1000))
  assert.equal(summarize(state, '2026-11').days[29].slots[23], 0.7)
  assert.equal(parts(at('2026-11-01T00:30:00'), 'Asia/Shanghai').day, '2026-10-31')
})
test('EO maps inferred before or after a direct reward never count twice', () => {
  for (const reverse of [false, true]) {
    const state = createLedger()
    const inputs = [bonus('2026-11-05T08:00:00', 75), maps('2026-11-05T08:01:00', [15])]
    for (const input of reverse ? inputs.reverse() : inputs) apply(state, input)
    apply(state, maps('2026-11-05T08:02:00', [15]))
    const report = summarize(state, '2026-11')
    assert.equal(report.eo, 75)
    assert.equal(report.unknownWithinMonth, 0)
  }
})
test('legacy inferred EO remains replayable but is excluded from unknown totals and month list', () => {
  const state = createLedger()
  apply(state, maps('2026-11-05T08:00:00', [15, 25]))
  apply(state, maps('2026-12-05T08:00:00', [15]))
  assert.equal(state.events.length, 3)
  assert.equal(summarize(state, '2026-11').unknownWithinMonth, 0)
  assert.equal(summarize(state, '2026-12').unknownWithinMonth, 0)
  assert.equal(summarize(state, '2026-11').unknown.length, 0)
  assert.deepEqual(months(state, 'Asia/Tokyo'), [])
  assert.equal(summarize(state, '2026-11').total, 0)
})
test('direct EO without map context is reconciled against the next map snapshot', () => {
  for (const reverse of [false, true]) {
    const state = createLedger()
    const inputs = [bonus('2026-11-05T08:00:00', 75, null), maps('2026-11-05T08:01:00', [15])]
    for (const input of reverse ? inputs.reverse() : inputs) apply(state, input)
    assert.equal(summarize(state, '2026-11').eo, 75)
    assert.equal(summarize(state, '2026-11').unknownWithinMonth, 0)
  }
})
test('equal-valued EO maps do not claim a specific missing map after an anonymous reward', () => {
  const state = createLedger()
  apply(state, maps('2026-11-04T08:00:00', [15]))
  apply(state, bonus('2026-11-05T08:00:00', 75, null))
  apply(state, maps('2026-11-05T08:01:00', [15, 16]))
  const report = summarize(state, '2026-11')
  assert.equal(report.total, 75)
  assert.equal(report.unknownWithinMonth, 0)
  assert.equal(report.unknown.length, 0)
  assert.match(state.events.find(e => e.source === 'unknown').label, /同额海域无法区分/)
})
test('daily and hourly activity excludes bonuses while top summaries retain them', () => {
  const state = createLedger()
  apply(state, exp('2026-11-05T08:00:00', 100000))
  apply(state, exp('2026-11-05T09:00:00', 101000, 1000))
  apply(state, bonus('2026-11-05T09:01:00', 75))
  apply(state, { ...bonus('2026-11-05T09:02:00', 350), kind: 'quest', mapId: null, questId: 854, key: 'quest:854', label: '任务奖励' })
  apply(state, maps('2026-11-05T09:03:00', [15, 25]))
  const report = summarize(state, '2026-11')
  const day = report.days[4]
  assert.equal(report.total, 425.7)
  assert.equal(report.eo, 75)
  assert.equal(report.quest, 350)
  assert.equal(day.total, 425.7)
  assert.equal(day.normal, 0.7)
  assert.equal(day.slots[9], 0.7)
  assert.equal(day.slots.reduce((sum, n) => sum + n, 0), 0.7)
  assert.equal(day.events.length, 1)
  assert.ok(day.events.every(e => e.kind === 'normal'))
  assert.equal(report.unknown.length, 0)
  const csv = toCSV(state, '2026-11', 'Asia/Tokyo')
  assert.match(csv, /"EO 战果","75.0000"/)
  assert.match(csv, /"任务战果","350.0000"/)
  assert.ok(!csv.includes('任务奖励'))
})
