test('adapter waits for account, accepts combined fleets, handles exact reward and strips secrets', () => {
  const adapter = createAdapter()
  const time = at('2026-11-05T08:00:00')
  assert.equal(decode(adapter, { path: '/kcsapi/api_req_sortie/battleresult', body: { api_member_exp: 1000 }, time }), null)
  decode(adapter, { path: '/kcsapi/api_port/port', time, body: { api_basic: { api_member_id: 123, api_experience: 100000 } } })
  decode(adapter, { path: '/kcsapi/api_req_map/start', time, body: { api_no: 1 }, postBody: { api_maparea_id: '5', api_mapinfo_no: '4' } })
  const decoded = decode(adapter, { path: '/kcsapi/api_req_combined_battle/battleresult', time, body: { api_member_exp: 101000, api_get_exp: 1000, api_win_rank: 'S' }, postBody: { api_token: 'SECRET' } })
  assert.equal(decoded.account, '123')
  assert.equal(decoded.records[0].gain, 1000)
  assert.match(decoded.records[0].label, /5-4/)
  assert.ok(!JSON.stringify(decoded).includes('SECRET'))
  decode(adapter, { path: '/kcsapi/api_start2/getData', body: {}, time })
  assert.equal(adapter.account, null)
})
test('quest rewards are response-only and deduplicated per quarterly cycle across New Year', () => {
  const adapter = createAdapter()
  adapter.account = '123'
  const state = createLedger()
  const claim = time => decode(adapter, { path: '/kcsapi/api_req_quest/clearitemget', time: at(time), body: {}, postBody: { api_quest_id: '854' } }).records[0]
  const december = claim('2026-12-20T08:00:00')
  const january = claim('2027-01-20T08:00:00')
  assert.equal(december.key, january.key)
  apply(state, december)
  apply(state, january)
  assert.equal(summarize(state, '2026-12').quest, 350)
  assert.equal(summarize(state, '2027-01').quest, 0)
  assert.notEqual(claim('2027-03-01T05:00:00').key, january.key)
  assert.equal(claim('2027-03-01T04:59:59').key, january.key)
})
test('CSV keeps unknown ranges distinct and escapes formula injection', () => {
  const state = createLedger()
  apply(state, exp('2026-11-05T08:00:00', 100000))
  apply(state, exp('2026-11-05T09:00:00', 110000))
  const csv = toCSV(state, '2026-11', 'Asia/Tokyo')
  assert.match(csv, /未定位/)
  assert.match(csv, /08:00:00/)
  assert.match(csv, /09:00:00/)
  assert.equal(cell('=1+1'), '"\'=1+1"')
})
